"""Caltrans PeMS Interface & Highway Corridor CLI and Backwards-Compatible Facade.

All core implementation lives in the modular ``pems`` package:
  - pems.config      Path defaults, HPMS endpoints/decoders, layer palettes, logging
  - pems.normalize   Route/direction/county/PM/coordinate/date normalization & safety guards
  - pems.client      Authenticated Caltrans PeMS HTTP session & query URL builders
  - pems.geo         Postmile spatial index, CA <-> Abs PM conversions, Census station matching
  - pems.projects    ProjectRecord model, Master CSV I/O & backups, ProjectPeMSQueryBuilder
  - pems.vds         PeMS VDS station metadata index & corridor detector comparison audit
  - pems.downloads   Multi-year PeMS station & project time-series CSV downloads
  - pems.corridor    Ad-hoc coordinate-range, postmile-range & HPMS corridor searches
  - pems.lane_config PeMS station lane config & TSN metric parser, scraper & JSON cache
  - pems.telemetry   Historical summary parsing & flow-activation Open-to-Traffic inference
  - pems.reporting   Pure-Python ASCII report tables and text/Markdown file exporters
  - pems.mapping     Interactive Folium project & corridor detector maps
  - pems.imagery     Esri Wayback historical imagery, curvature slicing & stacked strips
  - pems.web         Jinja2 research validation web dashboard & slices HTML report
  - pems.cli         Command-line argument parser and dispatch handlers
"""

